package Basics;

public class IncreDecre {
    public static void main(String[] args) {
        int x = 12;
        System.out.println(x);
        x++;
        System.out.println(x);

        int y = 20;
        System.out.println(y);
        y--;
        System.out.println(y);

        int result = 11;
        System.out.println(++result);
        System.out.println(result);

    }
}
