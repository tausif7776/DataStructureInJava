package DsaPractise;

public class Contains_Substring {
    public static void main(String[] args) {

        String main = "Hello World";
        String sub = "tausif";

        if (main.contains(sub)) {
            System.out.println("Yes, Contains Substring ");
        } else {
            System.out.println("NO, Contains Substring");
        }
    }
}
